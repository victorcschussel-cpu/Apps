import { DateTime } from 'luxon';
import { describe, expect, it } from 'vitest';
import { parseLibreViewCsv } from '../src/server/csvImport.js';

const sp = (iso: string) => DateTime.fromISO(iso, { zone: 'America/Sao_Paulo' }).toSeconds();

const PT = `Dados de glicose,Gerado em,25-10-2026 10:00 UTC,Gerado por,Fulano
Dispositivo,Número de série,Carimbo de data/hora do dispositivo,Tipo de registro,Histórico de glicose mg/dL,Glicose escaneada mg/dL,Insulina de ação rápida não numérica,Insulina de ação rápida (unidades),Alimentos não numéricos,Carboidratos (gramas),Carboidratos (porções),Insulina de ação longa não numérica,Insulina de ação longa (unidades),Notas,Tira de glicose mg/dL,Cetona mmol/L
FreeStyle LibreLink,ABC,20-10-2026 07:45,0,95,,,,,,,,,,,
FreeStyle LibreLink,ABC,20-10-2026 08:00,0,101,,,,,,,,,,,
FreeStyle LibreLink,ABC,20-10-2026 08:03,1,,104,,,,,,,,,,
FreeStyle LibreLink,ABC,20-10-2026 08:05,5,,,,,,45,,,,,,
FreeStyle LibreLink,ABC,20-10-2026 08:06,6,,,,,,,,,,café com pão,,
FreeStyle LibreLink,ABC,20-10-2026 08:20,0,,,,,,,,,,,,
FreeStyle LibreLink,ABC,31-02-2026 08:20,0,120,,,,,,,,,,,
`;

describe('parseLibreViewCsv', () => {
  it('lê histórico e escaneada (PT), ignora e conta o resto', () => {
    const r = parseLibreViewCsv(PT);
    expect(r.nRows).toBe(7);
    expect(r.readings).toEqual([
      { ts: sp('2026-10-20T07:45'), value: 95, kind: 'cgm' },
      { ts: sp('2026-10-20T08:00'), value: 101, kind: 'cgm' },
      { ts: sp('2026-10-20T08:03'), value: 104, kind: 'scan' },
    ]);
    expect(r.ignored).toEqual({ 'tipo 5': 1, 'tipo 6': 1, 'valor vazio (tipo 0)': 1, 'data inválida': 1 });
    expect(r.errors[0]).toContain('31-02-2026');
  });

  it('lê export em inglês, formato americano, mmol/L e BOM', () => {
    const EN = `﻿Glucose Data,Generated on,10-25-2026 10:00 AM UTC,Generated by,John
Device,Serial Number,Device Timestamp,Record Type,Historic Glucose mmol/L,Scan Glucose mmol/L
FreeStyle Libre 3,X,10-20-2026 07:45 AM,0,5.3,
FreeStyle Libre 3,X,10-20-2026 01:15 PM,1,,7.0
`;
    const r = parseLibreViewCsv(EN);
    expect(r.readings).toEqual([
      { ts: sp('2026-10-20T07:45'), value: 95, kind: 'cgm' },
      { ts: sp('2026-10-20T13:15'), value: 126, kind: 'scan' },
    ]);
  });

  it('aceita ";" como separador e vírgula decimal', () => {
    const r = parseLibreViewCsv(`Dados de glicose;Gerado em
Dispositivo;Número de série;Carimbo de data/hora do dispositivo;Tipo de registro;Histórico de glicose mmol/L;Glicose escaneada mmol/L
L;X;20/10/2026 07:45;0;5,3;
`);
    expect(r.readings).toEqual([{ ts: sp('2026-10-20T07:45'), value: 95, kind: 'cgm' }]);
  });

  it('rejeita arquivo que não é do LibreView', () => {
    expect(() => parseLibreViewCsv('a,b,c\n1,2,3')).toThrow(/Cabeçalho/);
  });
});
